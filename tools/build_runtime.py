"""Generate independent runtime distributions from maintained canonical sources."""
import argparse
import hashlib
import json
import io
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent
REPOS = ("iDirectory", "ThinkingSeed", "MetricsThinking", "iReadme", "ContextControl")


def put(path, raw, check=False):
    if path.is_file() and path.read_bytes() == raw:
        return False
    if check:
        raise ValueError(f"Generated distribution differs: {path.name}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(raw)
    return True


def build(check=False):
    runtime = (ROOT / "src/core/context_runtime.py").read_bytes()
    for path in (BASE / "MetricsThinking/src/metricsthinking/runtime.py", BASE / "iReadme/src/ireadme/runtime.py",
                 BASE / "ThinkingSeed/scripts/context_runtime.py"):
        put(path, runtime, check)
    for source in (BASE / "MetricsThinking/config/profiles").glob("*.yaml"):
        put(BASE / "MetricsThinking/src/metricsthinking/profiles" / source.name, source.read_bytes(), check)
    sources = {"fwengine.py": ROOT / "src/core/fwengine.py", "context_runtime.py": ROOT / "src/core/context_runtime.py"}
    for name in ("icontext_cli", "skill_installer", "benchmark"):
        sources[name + ".py"] = BASE / "ContextControl/src/core" / (name + ".py")
    for repo, package in (("MetricsThinking", "metricsthinking"), ("iReadme", "ireadme")):
        directory = BASE / repo / "src" / package
        # Domain-scoped source collection. Generated bytecode and data are excluded.
        for source in directory.rglob("*.py"):
            if "__pycache__" not in source.parts:
                sources[package + "/" + source.relative_to(directory).as_posix()] = source
    for source in (BASE / "MetricsThinking/config/profiles").glob("*.yaml"):
        sources["metricsthinking/profiles/" + source.name] = source
    for name in ("ThinkingSeed Master.md", "ThinkingSeed_MasterHybrid.md"):
        sources["seed_resources/" + name] = BASE / "ThinkingSeed" / name
    for repo, names in (("iDirectory", ["idir"]), ("ThinkingSeed", ["seed", "seed-master"]),
                        ("MetricsThinking", ["metrics"]), ("iReadme", ["readme"]), ("ContextControl", ["icontext"])):
        for name in names:
            bundle = BASE / repo / "skills/v6" / name
            manifest = json.loads((bundle / "bundle.json").read_text(encoding="utf-8"))
            for relative in ["bundle.json", *manifest["files"]]:
                sources[f"skill_bundles/{name}/{relative}"] = bundle / relative
    for source in (ROOT / "schemas").glob("*.schema.json"):
        sources["schemas/" + source.name] = source
    launcher = b'''#!/usr/bin/env python3
"""Compatibility launcher; generated from iDirectory/tools/build_runtime.py."""
from pathlib import Path
import sys
sys.dont_write_bytecode = True
_runtime_dir = Path(__file__).resolve().parent / "tools/icontext_runtime"
sys.path.insert(0, str(_runtime_dir))
if __name__ == "__main__" and sys.argv[1:2] == ["context"] and "--pack" in sys.argv[2:]:
    import argparse
    query = argparse.ArgumentParser(add_help=False)
    query.add_argument("--pack", required=True)
    query.add_argument("--tier", default="1a", choices=["1a", "1b", "2"])
    query.add_argument("--expand", action="store_true")
    options, unknown = query.parse_known_args(sys.argv[2:])
    if not unknown:
        from icontext_cli import main
        argv = ["pack", options.pack, "--tier", options.tier, "--json"]
        if options.expand:
            argv.append("--expand")
        raise SystemExit(main(argv))
exec(compile((_runtime_dir / "fwengine.py").read_text(encoding="utf-8"), str(_runtime_dir / "fwengine.py"), "exec"), globals())
'''
    writes = 0
    for repo in REPOS:
        target = BASE / repo / "tools/icontext_runtime"
        files = {}
        for relative, source in sources.items():
            raw = source.read_bytes()
            files[relative] = hashlib.sha256(raw).hexdigest()
            writes += put(target / relative, raw, check)
        # Wheels carry one deterministic payload so installation also works away
        # from the development checkout, with templates and bundle manifests.
        payload = io.BytesIO()
        with zipfile.ZipFile(payload, "w", zipfile.ZIP_DEFLATED) as archive:
            for relative, source in sorted(sources.items()):
                archive.writestr(zipfile.ZipInfo(relative, (2026, 1, 1, 0, 0, 0)), source.read_bytes(), compress_type=zipfile.ZIP_DEFLATED)
            embedded = {"version": "6.0.0", "files": dict(files)}
            archive.writestr(zipfile.ZipInfo("release_manifest.json", (2026, 1, 1, 0, 0, 0)), json.dumps(embedded, sort_keys=True), compress_type=zipfile.ZIP_DEFLATED)
        for relative, raw in {"_icontext_assets/__init__.py": b'"""Generated runtime payload."""\n',
                              "_icontext_assets/runtime_payload.zip": payload.getvalue()}.items():
            writes += put(target / relative, raw, check)
            files[relative] = hashlib.sha256(raw).hexdigest()
        writes += put(target / ".context.yaml", b'role: tooling\ncrawl: false\nread_priority: p3\nseed_reference: optional\npurpose: Generated versioned runtime; edit canonical source files.\n', check)
        manifest = {"version": "6.0.0", "origin": "iDirectory/src/core + ContextControl/src/core", "files": files}
        writes += put(target / "release_manifest.json", (json.dumps(manifest, sort_keys=True, indent=2) + "\n").encode(), check)
        writes += put(BASE / repo / "FWengine.py", launcher, check)
        for schema in (ROOT / "schemas").glob("*.schema.json"):
            if repo != "iDirectory":
                writes += put(BASE / repo / "schemas" / schema.name, schema.read_bytes(), check)
    # Packages and validators remain independently executable without sibling repos.
    for path in (BASE / "MetricsThinking/src/metricsthinking/runtime.py", BASE / "iReadme/src/ireadme/runtime.py",
                 BASE / "ThinkingSeed/scripts/context_runtime.py"):
        writes += put(path, runtime, check)
    print(json.dumps({"version": "6.0.0", "generated_writes": writes, "check": check}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
